# PROYECTO FINAL DE CALCULO DIFERENCIAL
# Rendimiento Maximo de Throughput en Servidores Web

import matplotlib.pyplot as plt
import os

# 1. Funcion del rendimiento
def throughput(x):
    return (500 * x) / (1 + 0.0025 * x**2)

# 2. Primera derivada
def primera_derivada(x):
    return (500 - 1.25 * x**2) / (1 + 0.0025 * x**2)**2

# 3. Segunda derivada
def segunda_derivada(x):
    return (2.5 * x * (0.0025 * x**2 - 3)) / (1 + 0.0025 * x**2)**3

# 4. Encontrar el numero optimo de hilos
hilos_optimos = 20

rendimiento_maximo = throughput(hilos_optimos)
primera = primera_derivada(hilos_optimos)
segunda = segunda_derivada(hilos_optimos)

# 5. Mostrar resultados principales
print("===== RESULTADOS DEL PROYECTO =====")
print("Hilos optimos:", hilos_optimos)
print("Throughput maximo:", rendimiento_maximo)
print("Primera derivada:", primera)
print("Segunda derivada:", segunda)

# 6. Crear una tabla de resultados
print("\n===== TABLA DE RENDIMIENTO =====")
print("Hilos | Throughput")

for x in range(0, 61, 5):
    print(x, "|", round(throughput(x), 2))

# 7. Crear los datos para la grafica
hilos = []
rendimientos = []

for x in range(0, 61):
    hilos.append(x)
    rendimientos.append(throughput(x))

# 8. Crear la carpeta de resultados
os.makedirs("resultados", exist_ok=True)

# 9. Graficar el rendimiento
plt.figure(figsize=(9, 5))

plt.plot(hilos, rendimientos, label="Throughput")

plt.scatter(
    hilos_optimos,
    rendimiento_maximo,
    color="red",
    label="Maximo rendimiento"
)

plt.xlabel("Numero de hilos concurrentes")
plt.ylabel("Transacciones por segundo")

plt.title("Rendimiento maximo de un servidor web")

plt.legend()
plt.grid()

# 10. Guardar la grafica
plt.savefig("resultados/grafica.png", dpi=300)

plt.show()

print("\nGrafica guardada correctamente.")

